-- (2.) Duplicated Find - 
-- duplicat Find - shopping_trends Table
SELECT
	CUSTOMER_ID,
	AGE,
	GENDER,
	ITEM_PURCHASED,
	CATEGORY,
	PURCHASE_AMOUNT_USD,
	COUNT(*)
FROM
	SHOPPING_TRENDS
GROUP BY
	CUSTOMER_ID,
	AGE,
	GENDER,
	ITEM_PURCHASED,
	CATEGORY,
	PURCHASE_AMOUNT_USD
HAVING
	COUNT(*) > 1;

