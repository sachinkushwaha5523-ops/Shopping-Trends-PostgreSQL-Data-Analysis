--(3.) Invalid Values check 
SELECT
	PURCHASE_AMOUNT_USD,
	REVIEW_RATING,
	PREVIOUS_PURCHASES,
	AGE
FROM
	SHOPPING_TRENDS
WHERE
	PURCHASE_AMOUNT_USD < 0
	OR REVIEW_RATING < 0
	OR PREVIOUS_PURCHASES < 0
	OR AGE < 0;

-- (4.) Invalid Entry check
SELECT
	SUBSCRIPTION_STATUS,
	PROMO_CODE_USED,
	PAYMENT_METHOD
FROM
	SHOPPING_TRENDS
WHERE
	SUBSCRIPTION_STATUS NOT IN ('Yes', 'No')
	OR PROMO_CODE_USED NOT IN ('Yes', 'No')
	OR PAYMENT_METHOD NOT IN (
		'PayPal',
		'Debit Card',
		'Credit Card',
		'Venmo',
		'Cash',
		'Bank Transfer'
	);

